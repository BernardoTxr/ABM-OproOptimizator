from __future__ import annotations
from collections import deque
from typing import Optional

from sortedcontainers import SortedDict

from .models import Order, Side, Trade


class LimitOrderBook:
    """
    Price-time priority (FIFO) limit order book for a single asset.

    Bid side: SortedDict keyed by -price so the smallest key (largest price)
    is the best bid. Ask side: SortedDict keyed by +price so the smallest
    key is the best ask. Each price level maps to a deque[Order] ordered
    by arrival time.

    An order registry provides O(1) lookup by order_id for cancellations.
    """

    def __init__(self) -> None:
        self._bids: SortedDict = SortedDict()   # key: -price → deque[Order]
        self._asks: SortedDict = SortedDict()   # key: +price → deque[Order]
        # Maps order_id → (Side, price) for O(1) cancel lookup
        self._registry: dict[str, tuple[Side, float]] = {}
        # Agents and the state recorder request the same depth snapshot many
        # times between book mutations.  Keep immutable cached levels so a
        # caller cannot mutate the cached representation through the lists
        # returned by ``get_snapshot``.
        self._snapshot_cache: dict[
            int,
            tuple[
                tuple[tuple[float, float], ...],
                tuple[tuple[float, float], ...],
            ],
        ] = {}

    # ------------------------------------------------------------------
    # Properties
    # ------------------------------------------------------------------

    @property
    def best_bid(self) -> Optional[float]:
        if not self._bids:
            return None
        return -self._bids.keys()[0]

    @property
    def best_ask(self) -> Optional[float]:
        if not self._asks:
            return None
        return self._asks.keys()[0]

    @property
    def mid_price(self) -> Optional[float]:
        bb, ba = self.best_bid, self.best_ask
        if bb is None or ba is None:
            return None
        return (bb + ba) / 2.0

    @property
    def spread(self) -> Optional[float]:
        bb, ba = self.best_bid, self.best_ask
        if bb is None or ba is None:
            return None
        return ba - bb

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def place_limit_order(self, order: Order, current_time: float) -> list[Trade]:
        """Insert a limit order. Returns any trades generated by crossing."""
        self._invalidate_snapshot_cache()
        trades: list[Trade] = []

        if order.side == Side.BUY:
            while order.remaining_qty > 0 and self._asks:
                best_ask_key = self._asks.keys()[0]
                if best_ask_key > order.price:
                    break
                self._match_level(order, self._asks, best_ask_key, current_time, trades)
                if best_ask_key in self._asks and not self._asks[best_ask_key]:
                    del self._asks[best_ask_key]
        else:
            while order.remaining_qty > 0 and self._bids:
                best_bid_key = self._bids.keys()[0]   # most negative = highest price
                best_bid_price = -best_bid_key
                if best_bid_price < order.price:
                    break
                self._match_level(order, self._bids, best_bid_key, current_time, trades)
                if best_bid_key in self._bids and not self._bids[best_bid_key]:
                    del self._bids[best_bid_key]

        if order.remaining_qty > 0:
            self._insert(order)

        return trades

    def place_market_order(self, order: Order, current_time: float) -> list[Trade]:
        """Sweep available levels until filled; remainder is silently discarded."""
        self._invalidate_snapshot_cache()
        trades: list[Trade] = []

        if order.side == Side.BUY:
            while order.remaining_qty > 0 and self._asks:
                best_ask_key = self._asks.keys()[0]
                self._match_level(order, self._asks, best_ask_key, current_time, trades)
                if best_ask_key in self._asks and not self._asks[best_ask_key]:
                    del self._asks[best_ask_key]
        else:
            while order.remaining_qty > 0 and self._bids:
                best_bid_key = self._bids.keys()[0]
                self._match_level(order, self._bids, best_bid_key, current_time, trades)
                if best_bid_key in self._bids and not self._bids[best_bid_key]:
                    del self._bids[best_bid_key]

        return trades

    def cancel_order(self, order_id: str) -> bool:
        """Remove a resting order. Returns True if found and removed."""
        if order_id not in self._registry:
            return False

        side, price = self._registry[order_id]

        if side == Side.BUY:
            level_key = -price
            levels = self._bids
        else:
            level_key = price
            levels = self._asks

        queue = levels.get(level_key)
        if queue is None:
            del self._registry[order_id]
            return False

        for i, o in enumerate(queue):
            if o.order_id == order_id:
                del queue[i]
                del self._registry[order_id]
                if not queue:
                    del levels[level_key]
                self._invalidate_snapshot_cache()
                return True

        del self._registry[order_id]
        return False

    def trim_to_depth(self, depth: int) -> list[Order]:
        """Remove every order resting beyond the best ``depth`` levels.

        Returns the removed orders so the environment can update agent state
        and emit cancellation reports.
        """
        if depth < 1:
            raise ValueError("LOB depth must be at least 1")

        removed: list[Order] = []
        for levels in (self._bids, self._asks):
            while len(levels) > depth:
                worst_key = levels.keys()[-1]
                queue = levels.pop(worst_key)
                for order in queue:
                    self._registry.pop(order.order_id, None)
                    removed.append(order)
        if removed:
            self._invalidate_snapshot_cache()
        return removed

    def get_snapshot(self, depth: int) -> tuple[list[tuple[float, float]], list[tuple[float, float]]]:
        """Return top-`depth` bid and ask levels as (price, qty) pairs, best first."""
        cached = self._snapshot_cache.get(depth)
        if cached is not None:
            return list(cached[0]), list(cached[1])

        bid_levels: list[tuple[float, float]] = []
        for key in list(self._bids.keys())[:depth]:
            qty = sum(o.remaining_qty for o in self._bids[key])
            bid_levels.append((-key, qty))

        ask_levels: list[tuple[float, float]] = []
        for key in list(self._asks.keys())[:depth]:
            qty = sum(o.remaining_qty for o in self._asks[key])
            ask_levels.append((key, qty))

        cached = (tuple(bid_levels), tuple(ask_levels))
        self._snapshot_cache[depth] = cached
        return list(cached[0]), list(cached[1])

    # ------------------------------------------------------------------
    # Internals
    # ------------------------------------------------------------------

    def _invalidate_snapshot_cache(self) -> None:
        self._snapshot_cache.clear()

    def _insert(self, order: Order) -> None:
        if order.side == Side.BUY:
            key = -order.price
            if key not in self._bids:
                self._bids[key] = deque()
            self._bids[key].append(order)
        else:
            key = order.price
            if key not in self._asks:
                self._asks[key] = deque()
            self._asks[key].append(order)

        self._registry[order.order_id] = (order.side, order.price)

    def _match_level(
        self,
        aggressor: Order,
        levels: SortedDict,
        level_key: float,
        current_time: float,
        trades: list[Trade],
    ) -> None:
        """Match aggressor against all orders in one price-level queue."""
        queue: deque[Order] = levels[level_key]
        trade_price = abs(level_key)   # bid key is negative, ask key is positive

        while queue and aggressor.remaining_qty > 0:
            resting = queue[0]
            fill_qty = min(aggressor.remaining_qty, resting.remaining_qty)

            if aggressor.side == Side.BUY:
                buyer_id, seller_id = aggressor.agent_id, resting.agent_id
            else:
                buyer_id, seller_id = resting.agent_id, aggressor.agent_id

            trades.append(Trade.create(
                aggressor_order_id=aggressor.order_id,
                resting_order_id=resting.order_id,
                buyer_agent_id=buyer_id,
                seller_agent_id=seller_id,
                price=trade_price,
                qty=fill_qty,
                timestamp=current_time,
                aggressor_side=aggressor.side,
            ))

            aggressor.remaining_qty -= fill_qty
            resting.remaining_qty -= fill_qty

            if resting.remaining_qty <= 0:
                queue.popleft()
                self._registry.pop(resting.order_id, None)
